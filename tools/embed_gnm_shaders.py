"""Regenerate and verify internal GCN shaders using the pinned host compilers."""
import argparse, hashlib, json, pathlib, subprocess, tempfile
from package_gnm_shader import compile_package

ROOT = pathlib.Path(__file__).resolve().parents[1]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--glslang', type=pathlib.Path, required=True)
    p.add_argument('--psbc', type=pathlib.Path, required=True)
    p.add_argument('--spirv-val', type=pathlib.Path)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    validator = (a.spirv_val or a.glslang.parent / 'spirv-val').resolve()
    if not validator.is_file():
        p.error('Pass the pinned --spirv-val executable')
    root = ROOT / 'src/gnm/shaders'
    lock = json.loads((ROOT / 'deps/toolchain-lock.json').read_text())
    metadata = {
        'schema': 1, 'target': 'base-PS4 GFX7',
        'dependencies': [entry for entry in lock['dependencies'] if entry['name'] in ['glslang', 'spirv-tools', 'spirv-headers', 'opengnm-psbc', 'opengnm']],
        'forks': json.loads((a.psbc.resolve().parent / 'build-provenance.json').read_text())['forks'],
        'generator_sha256': sha(pathlib.Path(__file__)),
        'packaging_sha256': sha(ROOT / 'tools/package_gnm_shader.py'),
        'validation_sha256': sha(ROOT / 'tools/validate_gnm_shader.py'),
        'stages': {},
    }
    output = ['// Generated by tools/embed_gnm_shaders.py; do not edit.\n',
              '// Pins, fork source identities and artifact hashes: resolve.provenance.json.\n']
    (ROOT / '.tmp').mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=ROOT / '.tmp', prefix='gnm-embed-') as directory:
        for name, stage in [('resolve.vert', 'vertex'), ('resolve.frag', 'fragment'), ('clear_depth.frag', 'fragment'), ('clear_color.frag', 'fragment'), ('copy_color.frag', 'fragment')]:
            suffix = name.replace('.', '_')
            source = root / name
            spv = pathlib.Path(directory) / (suffix + '.spv')
            native = pathlib.Path(directory) / (suffix + '.sb')
            subprocess.run([str(a.glslang.resolve()), '-V', '--target-env', 'vulkan1.0', str(source), '-o', str(spv)], check=True)
            subprocess.run([str(validator), '--target-env', 'vulkan1.0', str(spv)], check=True)
            compile_package(a.psbc, spv, stage, native)
            metadata['stages'][suffix] = {'source_sha256': sha(source), 'spirv_sha256': sha(spv), 'native_package_sha256': sha(native)}
            data = native.read_bytes()
            output += ['// Source SHA256 ' + sha(source) + '\n', 'static constexpr unsigned char ' + suffix + '[] = {\n']
            for start in range(0, len(data), 16):
                output.append('  ' + ','.join(f'0x{value:02x}' for value in data[start:start + 16]) + ',\n')
            output.append('};\n')
    outputs = {root / 'resolve.inc': ''.join(output), root / 'resolve.provenance.json': json.dumps(metadata, indent=2) + '\n'}
    for path, contents in outputs.items():
        if a.check:
            if not path.is_file() or path.read_text() != contents:
                raise RuntimeError(str(path) + ' differs from the pinned compiler output; regenerate it')
        elif not path.is_file() or path.read_text() != contents:
            path.write_text(contents)
    print('Internal GNM resolve artifacts match pinned sources and fork working trees')


if __name__ == '__main__':
    main()
