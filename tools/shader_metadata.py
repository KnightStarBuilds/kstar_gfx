"""Generate binding constants and opt-in assertions against consumer C structs."""
import hashlib,json,pathlib,re,sys

def ident(value):return re.sub('[^a-zA-Z0-9]','_',value).upper()
def emit(reflection,spirv,destination,source=None):
    data=json.loads(pathlib.Path(reflection).read_text());name=ident(pathlib.Path(spirv).name);prefix='KGFX_'+name
    lines=['/* Generated by kstar_gfx shader_metadata.py; do not edit. */',f'#ifndef {prefix}_H',f'#define {prefix}_H','#include <stdint.h>','#include <stddef.h>','#ifndef KGFX_SHADER_ASSERT','#ifdef __cplusplus','#define KGFX_SHADER_ASSERT static_assert','#else','#define KGFX_SHADER_ASSERT _Static_assert','#endif','#endif',f'#define {prefix}_LAYOUT_SHA256 "'+hashlib.sha256(json.dumps(data,sort_keys=True,separators=(',',':')).encode()).hexdigest()+'"']
    occupied=set()
    for kind in ['ubos','textures','separate_images','separate_samplers']:
        for item in data.get(kind,[]):
            if item.get('set',0)!=0:raise ValueError('v1 shaders require descriptor set 0')
            binding=item['binding']
            if binding in occupied:raise ValueError('Overlapping Vulkan descriptor binding '+str(binding))
            occupied.add(binding);symbol=prefix+'_'+ident(item['name'])
            logical=re.fullmatch('kgfx_[ut]([0-9]+)',item['name'])
            logical=int(logical[1]) if logical else binding if kind=='ubos' else binding-8
            if not 0<=logical<(4 if kind=='ubos' else 16):raise ValueError('Resource binding exceeds the v1 ABI: '+item['name'])
            expected=logical if kind=='ubos' else logical+8
            if binding!=expected:raise ValueError('Expected uniform binding N or texture binding N+8: '+item['name'])
            lines += [f'#define {symbol}_BINDING {logical}u',f'#define {symbol}_DESCRIPTOR_BINDING {binding}u']
            if kind=='ubos':
                size=item['block_size'];lines.append(f'#define {symbol}_SIZE {size}u');asserts=[f'KGFX_SHADER_ASSERT(sizeof(Type) == {size}, "uniform block size")']
                for member in data['types'][item['type']]['members']:
                    field=member['name'];offset=member['offset'];lines.append(f'#define {symbol}_{ident(field)}_OFFSET {offset}u');asserts.append(f'KGFX_SHADER_ASSERT(offsetof(Type, {field}) == {offset}, "uniform {field} offset")')
                lines.append(f'#define {symbol}_ASSERT_LAYOUT(Type) '+('; \\\n    '.join(asserts)))
    lines += ['#endif',''];pathlib.Path(destination).write_text('\n'.join(lines))
    root=pathlib.Path(__file__).resolve().parents[1]
    lock=json.loads((root/'deps/toolchain-lock.json').read_text())
    artifacts={}
    for suffix in ['.spv','.glsl','.gnm.spv','.json','.h']:
        path=pathlib.Path(str(spirv).removesuffix('.spv')+suffix)
        if path.exists():artifacts[path.name]=hashlib.sha256(path.read_bytes()).hexdigest()
    package={'schema':1,'entry_point':'main','stage':data['entryPoints'][0]['mode'],
             'layout_sha256':hashlib.sha256(json.dumps(data,sort_keys=True,separators=(',',':')).encode()).hexdigest(),
             'artifacts':artifacts,'targets':['GLSL 410 core','SPIR-V 1.0','base PS4 GFX7'],
             'compiler_sources':[x for x in lock['dependencies'] if x['name'] in ['glslang','spirv-cross','spirv-tools','spirv-headers','opengnm-psbc']]}
    if source:package['source_sha256']=hashlib.sha256(pathlib.Path(source).read_bytes()).hexdigest()
    pathlib.Path(str(spirv).removesuffix('.spv')+'.package.json').write_text(json.dumps(package,indent=2)+'\n')
if __name__=='__main__':emit(*sys.argv[1:])
